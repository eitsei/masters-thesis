    rq3_comps = [c for c in comparisons if c.target_rq == "RQ3"]

    latex_lines = [
        "\\begin{table}[p]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.4pt}",
        "\\renewcommand{\\arraystretch}{0.92}",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}} l l r r r r r r c @{}}",
        "\\toprule",
        "\\textbf{Configuration} & \\textbf{Evaluation Metric} & \\textbf{$C_0$ Med} & \\textbf{$C_k$ Med} & \\textbf{$\\tilde{\\mu}_\\Delta$} & \\textbf{$W$-Stat} & \\textbf{$p_{\\text{raw}}$} & \\textbf{$p_{\\text{adj}}$} & \\textbf{Sig} \\\\",
        "\\midrule",
    ]

    current_cfg = ""
    for comp in rq3_comps:
        if current_cfg and comp.config_name != current_cfg:
            latex_lines.append("\\addlinespace")

        cfg_display = _escape_latex(comp.config_name) if not comp.config_name.startswith("$") else comp.config_name
        cfg_col = cfg_display if comp.config_name != current_cfg else ""
        current_cfg = comp.config_name

        metric_tex = _escape_latex(comp.metric_name)
        base_str = f"{comp.baseline_median:.4f}"
        treat_str = f"{comp.treatment_median:.4f}"
        diff_str = f"{comp.median_diff:+.4f}"
        p_raw_str = f"{comp.p_raw:.2e}" if comp.p_raw < 0.001 else f"{comp.p_raw:.4f}"
        p_adj_str = f"{comp.p_adjusted:.2e}" if comp.p_adjusted < 0.001 else f"{comp.p_adjusted:.4f}"

        sig_tex = comp.significance
        if sig_tex != "ns":
            sig_tex = f"\\textbf{{{sig_tex}}}"

        row = (
            f"{cfg_col:15} & "
            f"{metric_tex:20} & "
            f"{base_str} & "
            f"{treat_str} & "
            f"{diff_str} & "
            f"{comp.w_statistic:.1f} & "
            f"{p_raw_str} & "
            f"{p_adj_str} & "
            f"{sig_tex} \\\\"
        )
        latex_lines.append(row)

    latex_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular*}",
            "\\vspace{0.5em}",
            "\\parbox{\\textwidth}{\\footnotesize",
            "\\textbf{Notes:} $\\tilde{\\mu}_\\Delta$ represents the median paired difference ($C_k - C_0$). Two-tailed Wilcoxon signed-rank test evaluated at $\\alpha = 0.05$. Family-wise error rate controlled via Holm-Bonferroni step-down adjusted $p$-values ($p_{\\text{adj}}$). Significance flags: $^{***}\\,p < 0.001$, $^{**}\\,p < 0.01$, $^{*}\\,p < 0.05$, $\\text{ns}\\,p \\ge 0.05$.}",
            "\\end{table}",
            "",
        ]
    )

    content = "\n".join(latex_lines)
    target_path.write_text(content, encoding="utf-8")
    return content


