def _escape_latex(text: str) -> str:
    """Escapes special LaTeX characters in plain text."""
    replacements = [
        ("\\", "\\textbackslash{}"),
        ("&", "\\&"),
        ("%", "\\%"),
        ("$", "\\$"),
        ("#", "\\#"),
        ("_", "\\_"),
        ("{", "\\{"),
        ("}", "\\}"),
        ("~", "\\textasciitilde{}"),
        ("^", "\\textasciicircum{}"),
    ]
    res = text
    for old, new in replacements:
        res = res.replace(old, new)
    return res


def export_benchmark_summary_latex(
    data: Sequence[Mapping[str, Any]] | dict[str, Sequence[Mapping[str, Any]]],
    output_path: Path | str = "thesis/tables/benchmark_summary.tex",
    label: str = "tab:benchmark_summary",
    caption: str = "Quantitative performance, operational cost, and response quality across RAG pipeline configurations.",
) -> str:
    """Exports benchmark summary table matching thesis publication formatting."""
    target_path = Path(output_path)
    target_path.parent.mkdir(parents=True, exist_ok=True)

    # Normalize data into dict
    run_dict: dict[str, Sequence[Mapping[str, Any]]]
    if isinstance(data, dict):
        run_dict = data
    else:
        run_dict = {"Baseline ($C_0$)": data}

    latex_lines = [
        "% Auto-generated by rag-evaluator export-thesis",
        "% Ready for \\input{tables/benchmark_summary.tex}",
        "\\begin{landscape}",
        "\\begin{table}[p]",
        "\\centering",
        "\\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}} l r r r r r r r r r r r r @{}}",
        "\\toprule",
        "\\textbf{Configuration} & \\textbf{$N$} & \\textbf{$P_{50}$} & \\textbf{$P_{95}$} & \\textbf{Tokens} & \\textbf{Cost (\\$)} & \\textbf{EM} & \\textbf{F1} & \\textbf{Faith} & \\textbf{AR} & \\textbf{CP} & \\textbf{CR} & \\textbf{Comp $Q$} \\\\",
        " & & \\scriptsize{(ms)} & \\scriptsize{(ms)} & \\scriptsize{avg} & \\scriptsize{per 1k q} & \\scriptsize{(\\%)} & \\scriptsize{(\\%)} & & & & & \\scriptsize{$[0,1]$} \\\\",
        "\\midrule",
    ]

    for name, records in run_dict.items():
        s = summarize_run_records(records)
        if not s:
            continue

        escaped_name = _escape_latex(name) if not name.startswith("$") else name
        em_pct = s["em_mean"] * 100.0
        f1_pct = s["f1_mean"] * 100.0

        row = (
            f"{escaped_name} & "
            f"{int(s['count'])} & "
            f"{s['latency_p50']:.1f} & "
            f"{s['latency_p95']:.1f} & "
            f"{s['tokens_mean']:.0f} & "
            f"\\${s['cost_mean'] * 1000.0:.3f} & "
            f"{em_pct:.1f}\\% & "
            f"{f1_pct:.1f}\\% & "
            f"{s['faithfulness_mean']:.3f} & "
            f"{s['answer_relevancy_mean']:.3f} & "
            f"{s['context_precision_mean']:.3f} & "
            f"{s['context_recall_mean']:.3f} & "
            f"\\textbf{{{s['composite_q_mean']:.4f}}} \\\\"
        )
        latex_lines.append(row)

    latex_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular*}",
            "\\vspace{0.5em}",
            "\\parbox{\\linewidth}{\\footnotesize",
            "\\textbf{Notes:} $P_{50}$ and $P_{95}$ represent median and 95th percentile end-to-end execution latencies. Cost reflects Google Cloud Gemini Enterprise platform pricing normalized per 1,000 queries. EM: Exact Match; F1: Token-level $F_1$; Faith: Faithfulness; AR: Answer Relevancy; CP: Context Precision; CR: Context Recall; Comp $Q$: Harmonic mean Composite Quality score (Eq.~238).}",
            "\\end{table}",
            "\\end{landscape}",
            "",
        ]
    )

    content = "\n".join(latex_lines)
    target_path.write_text(content, encoding="utf-8")
    return content


def export_hop_breakdown_latex(
    records: Sequence[Mapping[str, Any]],
    output_path: Path | str = "thesis/tables/hop_breakdown.tex",
    label: str = "tab:hop_breakdown",
    caption: str = "Benchmark evaluation performance stratified by MuSiQue reasoning depth tiers.",
) -> str:
    """Exports hop complexity breakdown table matching thesis publication formatting."""
    target_path = Path(output_path)
    target_path.parent.mkdir(parents=True, exist_ok=True)

    # Group by hopCount
    hop_groups: dict[int, list[Mapping[str, Any]]] = {}
    for r in records:
        hops = r.get("hopCount")
        if hops is None:
            hops = r.get("hop_count")
        if hops is None and "id" in r:
            rid = str(r["id"]).lower()
            if rid.startswith("1hop"):
                hops = 1
            elif rid.startswith("2hop"):
                hops = 2
            elif rid.startswith("3hop"):
                hops = 3
            elif rid.startswith("4hop"):
                hops = 4
            elif rid.startswith("ood"):
                hops = 0
        try:
            h_int = int(hops) if hops is not None else 0
        except (ValueError, TypeError):
            h_int = 0
        hop_groups.setdefault(h_int, []).append(r)

    latex_lines = [
        "% Auto-generated by rag-evaluator export-thesis",
        "% Ready for \\input{tables/hop_breakdown.tex}",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{2.6pt}",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}} l r r r r r r r r r r r @{}}",
        "\\toprule",
        "\\textbf{Reasoning Tier} & \\textbf{$N$} & \\textbf{$P_{50}$} & \\textbf{$P_{95}$} & \\makecell{\\textbf{Tokens}\\\\\\scriptsize{avg}} & \\makecell{\\textbf{Cost}\\\\\\scriptsize{(\\$/1k)}} & \\textbf{EM} & \\textbf{F1} & \\textbf{Faith} & \\textbf{AR} & \\textbf{CP} & \\makecell{\\textbf{Comp}\\\\\\textbf{$Q$}} \\\\",
        " & & \\scriptsize{(ms)} & \\scriptsize{(ms)} & & & \\scriptsize{(\\%)} & \\scriptsize{(\\%)} & & & & \\scriptsize{$[0,1]$} \\\\",
        "\\midrule",
    ]

    for h in sorted(hop_groups.keys()):
        h_recs = hop_groups[h]
        s = summarize_run_records(h_recs)
        tier_name = f"{h}-Hop Reasoning" if h > 0 else "Out-of-Domain"

        if s.get("answerable_count", 1) == 0:
            faith_str = "--"
            ar_str = "--"
            cp_str = "--"
            q_str = "--"
        else:
            faith_str = f"{s['faithfulness_mean']:.3f}"
            ar_str = f"{s['answer_relevancy_mean']:.3f}"
            cp_str = f"{s['context_precision_mean']:.3f}"
            q_str = f"\\textbf{{{s['composite_q_mean']:.4f}}}"

        row = (
            f"{tier_name} & "
            f"{int(s['count'])} & "
            f"{s['latency_p50']:.1f} & "
            f"{s['latency_p95']:.1f} & "
            f"{s['tokens_mean']:.0f} & "
            f"\\${s['cost_mean'] * 1000.0:.3f} & "
            f"{s['em_mean'] * 100:.1f}\\% & "
            f"{s['f1_mean'] * 100:.1f}\\% & "
            f"{faith_str} & "
            f"{ar_str} & "
            f"{cp_str} & "
            f"{q_str} \\\\"
        )
        latex_lines.append(row)

    # All queries row
    overall_s = summarize_run_records(records)
    if overall_s:
        latex_lines.append("\\midrule")
        total_row = (
            f"\\textbf{{Combined Corpus}} & "
            f"{int(overall_s['count'])} & "
            f"{overall_s['latency_p50']:.1f} & "
            f"{overall_s['latency_p95']:.1f} & "
            f"{overall_s['tokens_mean']:.0f} & "
            f"\\${overall_s['cost_mean'] * 1000.0:.3f} & "
            f"{overall_s['em_mean'] * 100:.1f}\\% & "
            f"{overall_s['f1_mean'] * 100:.1f}\\% & "
            f"{overall_s['faithfulness_mean']:.3f} & "
            f"{overall_s['answer_relevancy_mean']:.3f} & "
            f"{overall_s['context_precision_mean']:.3f} & "
            f"\\textbf{{{overall_s['composite_q_mean']:.4f}}} \\\\"
        )
        latex_lines.append(total_row)

    latex_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular*}",
            "\\vspace{0.5em}",
            "\\parbox{\\textwidth}{\\footnotesize",
            "\\textbf{Notes:} Evaluated over the MuSiQue multi-hop benchmark sample partitioned across 2-hop, 3-hop, and 4-hop questions. Costs reflect Google Cloud Gemini Enterprise platform pricing normalized per 1,000 queries. Metrics follow Chapter 4 definitions.}",
            "\\end{table}",
            "",
        ]
    )

    content = "\n".join(latex_lines)
    target_path.write_text(content, encoding="utf-8")
    return content


def export_wilcoxon_tests_latex(
    comparisons: Sequence[WilcoxonComparison],
    output_path: Path | str = "thesis/tables/wilcoxon_tests.tex",
    label: str = "tab:wilcoxon_results",
    caption: str = "Paired Wilcoxon signed-rank test results and Holm-Bonferroni step-down corrections (Thesis Table 4.2).",
) -> str:
    """Exports Table 4.2 Wilcoxon signed-rank tests matching thesis publication formatting."""
    target_path = Path(output_path)
    target_path.parent.mkdir(parents=True, exist_ok=True)

    latex_lines = [
        "% Auto-generated by rag-evaluator export-thesis",
        "% Ready for \\input{tables/wilcoxon_tests.tex}",
        "\\begin{table*}[!htbp]",
        "\\centering",
        "\\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}} l l l r r r r r r c @{}}",
        "\\toprule",
        "\\textbf{RQ} & \\textbf{Config} & \\textbf{Evaluation Metric} & \\textbf{$C_0$ Med} & \\textbf{$C_k$ Med} & \\textbf{$\\tilde{\\mu}_\\Delta$} & \\textbf{$W$-Stat} & \\textbf{$p_{\\text{raw}}$} & \\textbf{$p_{\\text{adj}}$} & \\textbf{Sig} \\\\",
        "\\midrule",
    ]

    current_rq = ""
    for comp in comparisons:
        if comp.target_rq != current_rq and current_rq != "":
            latex_lines.append("\\addlinespace")
        current_rq = comp.target_rq

        # Format numeric values
        base_str = (
            f"{comp.baseline_median:.4f}"
            if abs(comp.baseline_median) < 10
            else f"{comp.baseline_median:.1f}"
        )
        treat_str = (
            f"{comp.treatment_median:.4f}"
            if abs(comp.treatment_median) < 10
            else f"{comp.treatment_median:.1f}"
        )
        diff_str = (
            f"{comp.median_diff:+.4f}"
            if abs(comp.median_diff) < 10
            else f"{comp.median_diff:+.1f}"
        )

        p_raw_str = (
            f"{comp.p_raw:.2e}" if comp.p_raw < 0.001 else f"{comp.p_raw:.4f}"
        )
        p_adj_str = (
            f"{comp.p_adjusted:.2e}"
            if comp.p_adjusted < 0.001
            else f"{comp.p_adjusted:.4f}"
        )

        sig_tex = comp.significance
        if sig_tex != "ns":
            sig_tex = f"\\textbf{{{sig_tex}}}"

        cfg_name = _escape_latex(comp.config_name) if not comp.config_name.startswith("$") else comp.config_name
        metric_tex = _escape_latex(comp.metric_name)

        row = (
            f"{comp.target_rq} & "
            f"{cfg_name} & "
            f"{metric_tex} & "
            f"{base_str} & "
            f"{treat_str} & "
            f"{diff_str} & "
            f"{comp.w_statistic:.1f} & "
            f"{p_raw_str} & "
            f"{p_adj_str} & "
            f"{sig_tex} \\\\"
        )
        latex_lines.append(row)

    latex_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular*}",
            "\\vspace{0.5em}",
            "\\parbox{\\textwidth}{\\footnotesize",
            "\\textbf{Notes:} $\\tilde{\\mu}_\\Delta$ represents the median paired difference ($C_k - C_0$). Two-tailed Wilcoxon signed-rank test evaluated at $\\alpha = 0.05$. Family-wise error rate controlled via Holm-Bonferroni step-down adjusted $p$-values ($p_{\\text{adj}}$). Significance flags: $^{***}\\,p < 0.001$, $^{**}\\,p < 0.01$, $^{*}\\,p < 0.05$, $\\text{ns}\\,p \\ge 0.05$.}",
            "\\end{table*}",
            "",
        ]
    )

    content = "\n".join(latex_lines)
    target_path.write_text(content, encoding="utf-8")
    return content


